// Copy the @fontsource font files into public/fonts and generate a
// self-hosted @font-face stylesheet.
//
// The UnoCSS web-font preset with provider "fontsource" links the fonts
// straight to cdn.jsdelivr.net.  On a Chinese network (and on any
// exhibition machine without internet) those requests hang or get reset,
// which shows up as a console error and a visibly slow first paint.
// Self-hosting removes the external dependency completely.
import { existsSync, mkdirSync, readFileSync, writeFileSync, copyFileSync, readdirSync, unlinkSync } from 'node:fs'
import { dirname, join, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'

const here = dirname(fileURLToPath(import.meta.url))
const appRoot = resolve(here, '..')
const repoRoot = resolve(appRoot, '..', '..')
const pnpmRoot = join(repoRoot, 'node_modules', '.pnpm')
const outDir = join(appRoot, 'public', 'fonts')

// package directory name -> css file that holds the @font-face rules
const SOURCES = [
  ['@fontsource-variable+dm-sans@5.2.8', '@fontsource-variable/dm-sans', 'wght.css'],
  ['@fontsource-variable+nunito@5.2.7', '@fontsource-variable/nunito', 'wght.css'],
  ['@fontsource-variable+jura@5.2.7', '@fontsource-variable/jura', 'wght.css'],
  ['@fontsource-variable+quicksand@5.2.10', '@fontsource-variable/quicksand', 'wght.css'],
  ['@fontsource-variable+urbanist@5.2.7', '@fontsource-variable/urbanist', 'wght.css'],
  ['@fontsource-variable+comfortaa@5.2.8', '@fontsource-variable/comfortaa', 'wght.css'],
  ['@fontsource+dm-mono@5.2.7', '@fontsource/dm-mono', 'index.css'],
  ['@fontsource+dm-serif-display@5.2.8', '@fontsource/dm-serif-display', 'index.css'],
  ['@fontsource+gugi@5.2.7', '@fontsource/gugi', 'index.css'],
  ['@fontsource+kiwi-maru@5.2.8', '@fontsource/kiwi-maru', 'index.css'],
  ['@fontsource+m-plus-rounded-1c@5.2.10', '@fontsource/m-plus-rounded-1c', 'index.css'],
]

mkdirSync(outDir, { recursive: true })

// Drop the files a previous run left behind, so the folder only ever holds
// the fonts the current stylesheet actually references.
const keepNames = new Set()

const blocks = []
const copied = []
const missing = []

// Only the latin and latin-ext subsets of the upright faces are kept: the
// interface is Chinese, and the Japanese/italic/opsz variants would add
// several megabytes for glyphs nothing on screen ever uses.
const KEEP_RANGES = ['U+0000-00FF', 'U+0100-02BA']

for (const [dirName, pkgName, cssFile] of SOURCES) {
  const pkgDir = join(pnpmRoot, dirName, 'node_modules', pkgName)
  const cssPath = join(pkgDir, cssFile)
  if (!existsSync(cssPath)) {
    missing.push(pkgName)
    continue
  }
  const css = readFileSync(cssPath, 'utf8')
  const faces = css.match(/@font-face\s*\{[^}]*\}/g) || []
  const kept = []
  for (const face of faces) {
    if (!/font-style:\s*normal/.test(face))
      continue
    const range = face.match(/unicode-range:\s*([^;]+);/)?.[1] ?? ''
    if (!KEEP_RANGES.some(marker => range.includes(marker)))
      continue
    const ref = face.match(/url\(\.\/files\/([^)]+\.woff2)\)/)?.[1]
    if (!ref)
      continue
    const src = join(pkgDir, 'files', ref)
    if (!existsSync(src)) {
      missing.push(`${pkgName}/${ref}`)
      continue
    }
    copyFileSync(src, join(outDir, ref))
    copied.push(ref)
    keepNames.add(ref)
    kept.push(face.replace(/url\(\.\/files\/([^)]+)\)/g, 'url(/fonts/$1)'))
  }
  if (kept.length)
    blocks.push(`/* ${pkgName} */\n${kept.join('\n')}`)
}

for (const name of readdirSync(outDir)) {
  if (name.endsWith('.woff2') && !keepNames.has(name))
    unlinkSync(join(outDir, name))
}

const header = [
  '/*',
  ' * Self-hosted web fonts.',
  ' *',
  ' * Generated by scripts/self-host-fonts.mjs -- do not edit by hand.',
  ' * The fonts used to be pulled from cdn.jsdelivr.net at runtime, which',
  ' * fails (or stalls) whenever the machine has no access to that CDN.',
  ' */',
  '',
].join('\n')

const cssPath = join(appRoot, 'src', 'styles', 'self-hosted-fonts.css')
mkdirSync(dirname(cssPath), { recursive: true })
writeFileSync(cssPath, `${header}${blocks.join('\n\n')}\n`, 'utf8')

console.log(`copied ${copied.length} font files -> ${outDir}`)
console.log(`wrote ${cssPath}`)
if (missing.length)
  console.log(`MISSING (${missing.length}): ${missing.join(', ')}`)
